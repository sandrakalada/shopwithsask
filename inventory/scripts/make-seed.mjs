// Builds supabase/seed.sql from the live store's public product feed
// (https://shopwithsask.com/products.json) plus supabase/qty-overrides.json.
// Barcode for each size = "SWS" + last 7 digits of its Shopify variant id, so the
// seed can be re-run safely (existing rows are left untouched).
import { readFileSync, writeFileSync } from "node:fs";

const overrides = JSON.parse(readFileSync(new URL("../supabase/qty-overrides.json", import.meta.url)));
const q = (v) => (v == null || v === "" ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const uuidFromId = (prefix, id) => {
  const hex = (prefix + BigInt(id).toString(16)).padStart(32, "0").slice(-32);
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
};

const products = [];
for (let page = 1; ; page++) {
  const res = await fetch(`https://shopwithsask.com/products.json?limit=250&page=${page}`, { headers: { "user-agent": "Mozilla/5.0" } });
  const { products: batch } = await res.json();
  products.push(...batch);
  if (batch.length < 250) break;
}

const pRows = [];
const vRows = [];
for (const p of products) {
  const pid = uuidFromId("a", p.id);
  pRows.push(`(${q(pid)}, ${q(p.handle)}, ${q(p.title)}, ${q(p.product_type)}, ${q(p.images?.[0]?.src?.split("?")[0])})`);
  for (const v of p.variants) {
    const qty = overrides[String(v.id)] ?? (v.available ? 1 : 0);
    vRows.push(
      `(${q(uuidFromId("b", v.id))}, ${q(pid)}, ${q(v.title)}, ${q(v.sku)}, ${q(`SWS${String(v.id).slice(-7)}`)}, ${Number(v.price) || "null"}, ${qty}, ${q(String(v.id))})`,
    );
  }
}

writeFileSync(
  new URL("../supabase/seed.sql", import.meta.url),
  `-- Generated by scripts/make-seed.mjs on ${new Date().toISOString().slice(0, 10)}. Run after schema.sql.
insert into public.products (id, handle, title, product_type, image_url) values
${pRows.join(",\n")}
on conflict do nothing;

insert into public.variants (id, product_id, title, sku, barcode, price, quantity, shopify_variant_id) values
${vRows.join(",\n")}
on conflict do nothing;
`,
);
console.log(`seed.sql: ${pRows.length} products, ${vRows.length} variants`);
