// Runs after `next build`: writes out/sw.js with a precache list of every file in
// the static export, so the installed app opens and works with no connection.
import { readdirSync, statSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { createHash } from "node:crypto";

const OUT = new URL("../out/", import.meta.url).pathname;
const files = [];
(function walk(dir) {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) walk(p);
    else files.push("/" + relative(OUT, p).split("\\").join("/"));
  }
})(OUT);

// pages are served at clean addresses (/orders, not /orders.html) by the host
const precache = files
  // the photo-recognition model (26 MB) is downloaded the first time Find my product is opened, not at install
  .filter((f) => f !== "/sw.js" && f !== "/version.json" && !f.endsWith(".map") && !f.startsWith("/404") && !f.startsWith("/_not-found") && !f.startsWith("/models/") && !f.startsWith("/ort/") && !f.startsWith("/ocr/") && f !== "/find-index.json" && !/\/ort-wasm/.test(f))
  .map((f) => (f === "/index.html" ? "/" : f.endsWith(".html") ? f.slice(0, -5) : f));
const hash = createHash("sha1");
for (const f of files) if (f !== "/sw.js") hash.update(f).update(readFileSync(join(OUT, f)));
const version = hash.digest("hex").slice(0, 12);

const sw = `// generated by scripts/build-sw.mjs
const VERSION = ${JSON.stringify(version)};
const APP = "app-" + VERSION;
const IMG = "img-v1";
const AI = "ai-v1";
const PRECACHE = ${JSON.stringify(precache)};

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(APP).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== APP && k !== IMG && k !== AI).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

function pageKey(pathname) {
  if (pathname === "/" || pathname === "") return "/";
  return pathname.replace(/\\/$/, "").replace(/\\.html$/, "");
}

self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);

  // product photos: keep a copy so they show offline
  if (url.hostname === "cdn.shopify.com") {
    e.respondWith(
      caches.open(IMG).then(async (c) => {
        const hit = await c.match(req);
        if (hit) return hit;
        try {
          const res = await fetch(req);
          if (res.ok || res.type === "opaque") c.put(req, res.clone());
          return res;
        } catch {
          return new Response("", { status: 504 });
        }
      }),
    );
    return;
  }
  if (url.origin !== self.location.origin) return; // Supabase etc. go straight to the network
  if (url.pathname === "/version.json") return; // always from the network

  // recognition model and engine: downloaded once, then kept (they never change for a given file name)
  if (url.pathname.startsWith("/models/") || url.pathname.startsWith("/ort/") || url.pathname.startsWith("/ocr/")) {
    e.respondWith(
      caches.open(AI).then(async (c) => {
        const hit = await c.match(req);
        if (hit) return hit;
        const res = await fetch(req);
        if (res.ok) c.put(req, res.clone());
        return res;
      }),
    );
    return;
  }
  // product photo index: newest when online, saved copy offline
  if (url.pathname === "/find-index.json") {
    e.respondWith(
      caches.open(AI).then(async (c) => {
        try {
          const res = await fetch(req, { cache: "no-store" });
          if (res.ok) c.put(url.pathname, res.clone());
          return res;
        } catch {
          return (await c.match(url.pathname)) || Response.error();
        }
      }),
    );
    return;
  }

  e.respondWith(
    (async () => {
      const cache = await caches.open(APP);
      // pages and page data: straight from this version's saved copy (instant, works with no or weak signal).
      // A new version installs a new service worker with its own copies, and the app reloads onto it.
      const isPage = req.mode === "navigate" || url.pathname.endsWith(".txt") || url.searchParams.has("_rsc");
      if (isPage) {
        const key = req.mode === "navigate" ? pageKey(url.pathname) : url.pathname;
        const hit = (await cache.match(key)) || (await cache.match(url.pathname));
        if (hit) return hit;
        try {
          return await fetch(req);
        } catch {
          return (await cache.match("/")) || Response.error();
        }
      }
      // scripts, styles, images: file names change with every version, so the saved copy is always right
      const hit = (await cache.match(url.pathname)) || (await cache.match(req, { ignoreSearch: true }));
      if (hit) return hit;
      try {
        const res = await fetch(req);
        if (res.ok && url.pathname.startsWith("/_next/")) cache.put(url.pathname, res.clone());
        return res;
      } catch {
        return Response.error();
      }
    })(),
  );
});
`;
writeFileSync(join(OUT, "sw.js"), sw);
console.log(`sw.js: ${precache.length} files, version ${version}`);
